export function hash(str) {
  let h = 5381;
  for (const ch of String(str)) h = ((h << 5) + h + ch.charCodeAt(0)) | 0;
  return Math.abs(h);
}

export function fill(template, vars = {}) {
  return template
    .replace('{, name}', vars.name ? `, ${vars.name}` : '')
    .replace(/\{(\w+)\}/g, (_, k) => (vars[k] === undefined || vars[k] === null ? '' : String(vars[k])));
}

export function pickLine(situation, { seed = '', shift = 0, vars = {} } = {}) {
  const list = LINES[situation] || LINES.happy_idle;
  const idx = (hash(`${seed}|${situation}`) + shift) % list.length;
  return fill(list[idx], vars);
}
